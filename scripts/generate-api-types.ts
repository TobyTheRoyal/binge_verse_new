import { readFile, writeFile } from "node:fs/promises";
import { codegen } from "@graphql-codegen/core";
import * as typescript from "@graphql-codegen/typescript";
import * as resolvers from "@graphql-codegen/typescript-resolvers";
import { parse } from "graphql";
import { format, resolveConfig } from "prettier";
import ts from "typescript";
import { typeDefs } from "../server/graphql/schema.js";

const target = new URL("../shared/api.generated.ts", import.meta.url);
const output = await codegen({
  filename: target.pathname,
  schema: parse(typeDefs),
  documents: [],
  config: {
    enumsAsTypes: true,
    avoidOptionals: { field: true },
    useTypeImports: true,
    contextType: "../server/auth.js#AuthContext",
    scalars: { ID: "string", Int: "number", Float: "number", String: "string", Boolean: "boolean" },
  },
  plugins: [{ typescript: {} }, { resolvers: {} }],
  pluginMap: { typescript, resolvers },
});
// The upstream generator uses any in unused subscription helpers. Keep these boundaries unknown.
const tree = ts.createSourceFile("api.ts", output, ts.ScriptTarget.Latest, true);
const spans: Array<[number, number]> = [];
function visit(node: ts.Node) {
  if (node.kind === ts.SyntaxKind.AnyKeyword) spans.push([node.getStart(tree), node.end]);
  ts.forEachChild(node, visit);
}
visit(tree);
let typedOutput = output;
for (const [start, end] of spans.sort((a, b) => b[0] - a[0]))
  typedOutput = typedOutput.slice(0, start) + "unknown" + typedOutput.slice(end);
const source = await format(
  `// Generated by npm run generate:api. Do not edit manually.\n${typedOutput}`,
  { ...(await resolveConfig(target.pathname)), parser: "typescript" },
);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== source)
    throw new Error("API types are stale. Run npm run generate:api.");
} else {
  await writeFile(target, source);
}
